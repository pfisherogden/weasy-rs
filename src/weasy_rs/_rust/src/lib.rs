//! `weasy-rs`: High-performance Rust HTML + CSS Paged Media to PDF rendering engine.
//!
//! Designed as a drop-in, native Rust replacement for WeasyPrint (`weasyprint.HTML`)
//! for structured multi-column, table-heavy, and paged reports.

pub mod css;
pub mod fonts;
pub mod html;
pub mod layout;
pub mod pdf;
pub mod py_bridge;

pub use layout::render_html_to_pdf;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_basic_html_to_pdf() {
        let html = r#"
        <!DOCTYPE html>
        <html>
        <head>
            <style>
                @page { size: letter; margin: 0.5in; margin-top: 1.25in; }
                #header { position: running(header); border-bottom: 1pt solid #000; }
                .content-container { column-count: 2; column-gap: 30pt; column-rule: 1pt solid #ddd; }
                .event-header-box { background-color: #f0f0f0; font-weight: bold; padding: 2pt 4pt; border: 1pt solid #999; }
                .div-entry-row { display: table; width: 100%; max-width: 255pt; table-layout: fixed; }
                .div-col { display: table-cell; padding: 0 4pt; }
                .col-lane { width: 20pt; text-align: center; }
                .col-name { width: 88pt; }
                .col-time { width: 45pt; text-align: right; }
            </style>
        </head>
        <body>
            <div id="header">Meet Program - Page <span class="page-counter"></span></div>
            <div class="content-container">
                <div class="event-header-box">Event 1 Girls 100 Yard Medley Relay</div>
                <div class="div-entry-row">
                    <div class="div-col col-lane">1</div>
                    <div class="div-col col-name">Del Prado Stingrays</div>
                    <div class="div-col col-time">1:45.23</div>
                </div>
            </div>
        </body>
        </html>
        "#;
        let pdf = render_html_to_pdf(html, None);
        assert!(pdf.starts_with(b"%PDF-1.4"));
        assert!(pdf.ends_with(b"%%EOF\n"));
        assert!(pdf.len() > 500);
    }

    #[test]
    fn test_landscape_and_margin_boxes() {
        let html = r#"
        <!DOCTYPE html>
        <html>
        <head>
            <style>
                @page {
                    size: letter landscape;
                    margin: 0.4in;
                    @bottom-left { content: "Generated by MMTools"; font-size: 8pt; color: #666666; }
                    @bottom-right { content: "Page " counter(page) " of " counter(pages); font-size: 8pt; color: #666666; }
                }
                .summary-strip { display: flex; gap: 12pt; }
                .summary-card { background-color: #f8f9fa; padding: 8pt; border: 1pt solid #ddd; }
                .badge { background-color: #fef08a; padding: 2pt 5pt; border-radius: 3pt; font-weight: bold; }
            </style>
        </head>
        <body>
            <div class="summary-strip">
                <div class="summary-card">Total PBs: 120</div>
                <div class="summary-card">Swimmers: 65</div>
            </div>
            <table>
                <thead>
                    <tr><th width="50%">Swimmer</th><th width="50%">Drop</th></tr>
                </thead>
                <tbody>
                    <tr><td>Jane Doe</td><td><span class="badge">-1.45</span></td></tr>
                </tbody>
            </table>
        </body>
        </html>
        "#;
        let pdf = render_html_to_pdf(html, None);
        assert!(pdf.starts_with(b"%PDF-1.4"));
        let text = String::from_utf8_lossy(&pdf);
        assert!(text.contains("/MediaBox [0 0 792.00 612.00]"));
    }
}
